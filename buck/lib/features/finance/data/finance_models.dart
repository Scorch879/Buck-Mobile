    walletId: row['wallet_id'] as String?,
    source: (row['source'] as String?) ?? 'Other',
    amount: _toDouble(row['amount']),
    receivedOn: _parseDate(row['received_on']) ?? DateTime.now(),
  );
}

/// `ai_advisories` row (generated by the web AI advisor).
class AiAdvisory {
  final String id;
  final String title;
  final String suggestion;
  final String advice;

  const AiAdvisory({
    required this.id,
    required this.title,
    required this.suggestion,
    required this.advice,
  });

  /// The most useful single line to show in the banner.
  String get text {
    for (final candidate in [suggestion, advice, title]) {
      if (candidate.trim().isNotEmpty) return candidate.trim();
    }
    return '';
  }

  factory AiAdvisory.fromRow(Map<String, dynamic> row) => AiAdvisory(
    id: row['id'] as String,
    title: (row['title'] as String?) ?? '',
    suggestion: (row['suggestion'] as String?) ?? '',
    advice: (row['advice'] as String?) ?? '',
  );
}
