/// Plain data rows read from the shared Buck Supabase database.
library;

double _toDouble(Object? value) {
  if (value is num) return value.toDouble();
  if (value is String) return double.tryParse(value) ?? 0;
  return 0;
}

/// Parses a Postgres `date` ("YYYY-MM-DD") as a local calendar date.
DateTime? _parseDate(Object? value) {
  if (value is! String) return null;
  final match = RegExp(r'^(\d{4})-(\d{2})-(\d{2})').firstMatch(value);
  if (match == null) return DateTime.tryParse(value)?.toLocal();
  return DateTime(
    int.parse(match.group(1)!),
    int.parse(match.group(2)!),
    int.parse(match.group(3)!),
  );
}

/// `wallets` row. `budget` is the wallet's current balance.
class Wallet {
  final String id;
  final String name;
  final double balance;

  const Wallet({required this.id, required this.name, required this.balance});

  factory Wallet.fromRow(Map<String, dynamic> row) => Wallet(
    id: row['id'] as String,
    name: (row['name'] as String?)?.trim() ?? 'Wallet',
    balance: _toDouble(row['budget']),
  );
}

/// `expenses` row.
class ExpenseRecord {
  final String id;
  final String? walletId;
  final String categoryName;
  final double amount;
  final String description;
  final DateTime spentOn;

  const ExpenseRecord({
    required this.id,
    required this.walletId,
    required this.categoryName,
    required this.amount,
    required this.description,
    required this.spentOn,
  });

  factory ExpenseRecord.fromRow(Map<String, dynamic> row) => ExpenseRecord(
    id: row['id'] as String,
    walletId: row['wallet_id'] as String?,
    categoryName: (row['category_name'] as String?)?.trim().isNotEmpty == true
        ? (row['category_name'] as String).trim()
        : 'Uncategorized',
    amount: _toDouble(row['amount']),
    description: (row['description'] as String?) ?? '',
    spentOn: _parseDate(row['spent_on']) ?? DateTime.now(),
  );
}

/// `incomes` row.
class IncomeRecord {
  final String id;
  final String? walletId;
  final String source;
  final double amount;
  final DateTime receivedOn;

  const IncomeRecord({
    required this.id,
    required this.walletId,
    required this.source,
    required this.amount,
    required this.receivedOn,
  });

  factory IncomeRecord.fromRow(Map<String, dynamic> row) => IncomeRecord(
